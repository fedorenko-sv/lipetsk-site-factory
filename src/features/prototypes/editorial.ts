export function withEditorialResourceNames(config: SiteConfig): SiteConfig {
  if (config.resources.length === 0) return config;
  return {
    ...config,
    resources: config.resources.map(resource => {
      const person = people[resource.id];
      return person ? { ...resource, name: person[0] + " · демо" } : resource;
    }),
  };
}


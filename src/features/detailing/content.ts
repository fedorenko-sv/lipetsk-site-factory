export const programs = copy.map((item) => {
  const service = siteConfig.services.find((s) => s.id === item.id);
  if (!service) throw new Error("Missing configured detailing service: " + item.id);
  return { ...item, service };
});
export type Program = (typeof programs)[number];
export function findProgram(id: unknown): Program | undefined {
  return typeof id === "string" ? programs.find((p) => p.id === id) : undefined;
}
export function resolveCategory(value: unknown): Category {
  return typeof value === "string" && categories.some((c) => c.id === value)
    ? (value as Category)
    : "all";
}
export function filterPrograms(category: Category) {
  return category === "all" ? programs : programs.filter((p) => p.category === category);
}
export function bookingHref(id?: unknown) {
  const program = findProgram(id);
  return basePath + "/booking" + (program ? "?service=" + encodeURIComponent(program.id) : "");
}
